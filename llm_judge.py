"""LLM-as-a-judge (paper, Sec. 4 and Fig. 3).

For every volume shared by all report files, one prompt shows the ground-truth report and
all candidate reports; the judge returns integer scores (0-10) per candidate on five
criteria. Backends: ``vllm`` (open-weight model, e.g. Qwen2.5-72B-Instruct) or ``gemini``
(Google GenAI API, set GEMINI_API_KEY).
"""
import csv
import json
import os
import re

from src.config import base_parser, resolve_config, resolve_path
from src.data import load_reports

SHORTCUTS = {"backend": "judge.backend", "model": "judge.model", "limit": "judge.limit",
             "output_dir": "judge.output_dir"}

CRITERIA = [
    "factual_clinical_accuracy",
    "global_medical_coherence",
    "impression_quality",
    "radiology_style_formalism",
    "clinical_safety",
]


def truncate(text, max_chars):
    text = (text or "").strip()
    return text if len(text) <= max_chars else text[:max_chars - 20].rstrip() + "\n\n[TRUNCATED]"


def build_judge_prompt(volume_id, ground_truth, candidates, max_chars=2200):
    blocks = "\n\n".join(f"### CANDIDATE REPORT ({name})\n{truncate(report, max_chars)}"
                         for name, report in candidates.items())
    return f"""You are a board-certified radiologist auditing generated radiology reports.
You will be given:
(1) the Ground Truth report written by a physician
(2) multiple Candidate reports generated by different models

Task:
For EACH candidate report, independently assign five integer scores from 0 to 10 (inclusive) using the criteria below, strictly by comparing to the Ground Truth.

Scoring criteria (0-10, integers only):
1) factual_clinical_accuracy:
   - Does the candidate match the Ground Truth facts (findings, laterality, presence/absence, key diagnoses)?
   - Penalize hallucinations, missing critical findings, wrong anatomy, wrong conclusions.
2) global_medical_coherence:
   - Are Findings and Impression internally consistent? No contradictions, no impossible combinations.
3) impression_quality:
   - Is the Impression a faithful, cautious, clinically appropriate synthesis of the candidate's Findings AND aligned with Ground Truth?
   - Penalize overconfident claims, omission of critical conclusions, or mismatch with findings.
4) radiology_style_formalism:
   - Professional radiology writing: structure, clarity, standard phrasing, appropriate hedging, no irrelevant text.
5) clinical_safety:
   - Could this report cause clinical harm if used in real practice?
   - Consider missed critical pathology, incorrect urgent statements, unsafe recommendations, misleading certainty.

Rubric anchor points:
- 10 = excellent / essentially matches GT with no clinically meaningful issues
- 7-9 = minor issues, unlikely to change management
- 4-6 = noticeable errors/omissions; could affect management
- 1-3 = major errors; unsafe or very misleading
- 0 = completely incorrect / unusable / dangerously wrong

Output format (STRICT JSON ONLY, no markdown, no extra keys, no commentary):
{{
  "volume_name": "{volume_id}",
  "scores": {{
    "<MODEL_NAME>": {{
      "factual_clinical_accuracy": <int 0-10>,
      "global_medical_coherence": <int 0-10>,
      "impression_quality": <int 0-10>,
      "radiology_style_formalism": <int 0-10>,
      "clinical_safety": <int 0-10>
    }},
    "...": {{ ... }}
  }}
}}

Models to score (must match keys exactly): {json.dumps(list(candidates))}

=== GROUND TRUTH REPORT ===
{truncate(ground_truth, max_chars)}

=== CANDIDATE REPORTS ===
{blocks}

Remember: return STRICT JSON ONLY.
"""


def parse_scores(text, model_names):
    """Extract and validate the JSON answer; scores are clipped to integers in [0, 10]."""
    match = re.search(r"\{.*\}", text or "", re.DOTALL)
    if not match:
        raise ValueError("no JSON object in the judge output")
    scores = json.loads(match.group(0))["scores"]
    return {name: {c: max(0, min(10, int(round(float(scores[name][c]))))) for c in CRITERIA}
            for name in model_names}


class VLLMJudge:
    def __init__(self, cfg):
        from vllm import LLM, SamplingParams

        self.llm = LLM(model=cfg["model"], dtype="bfloat16", tensor_parallel_size=cfg["tensor_parallel_size"],
                       gpu_memory_utilization=cfg["gpu_memory_utilization"],
                       max_model_len=cfg["max_model_len"], trust_remote_code=True)
        self.params = SamplingParams(max_tokens=cfg["max_tokens"], temperature=0)

    def __call__(self, prompts):
        return [out.outputs[0].text for out in self.llm.generate(prompts, sampling_params=self.params)]


class GeminiJudge:
    def __init__(self, cfg):
        from google import genai
        from google.genai import types

        self.client = genai.Client()  # reads GEMINI_API_KEY
        self.model = cfg["model"]
        self.config = types.GenerateContentConfig(temperature=0, response_mime_type="application/json")

    def __call__(self, prompts):
        return [self.client.models.generate_content(model=self.model, contents=p, config=self.config).text
                for p in prompts]


def main():
    parser = base_parser(__doc__)
    parser.add_argument("--backend", choices=["vllm", "gemini"])
    parser.add_argument("--model", help="Judge model (e.g. Qwen/Qwen2.5-72B-Instruct or gemini-2.5-pro).")
    parser.add_argument("--limit", type=int, help="Only judge the first N common volumes.")
    parser.add_argument("--output_dir")
    parser.add_argument("--max_retries", type=int, default=2)
    args = parser.parse_args()
    cfg = resolve_config(args, SHORTCUTS)["judge"]

    ground_truth = load_reports(resolve_path(cfg["ground_truth"]))
    candidates = {name: load_reports(resolve_path(path)) for name, path in cfg["reports"].items()}
    volumes = sorted(set(ground_truth).intersection(*candidates.values()))
    if cfg["limit"]:
        volumes = volumes[:cfg["limit"]]
    names = list(candidates)
    print(f"Judging {len(volumes)} volumes x {len(names)} models with {cfg['backend']}:{cfg['model']}")

    judge = VLLMJudge(cfg) if cfg["backend"] == "vllm" else GeminiJudge(cfg)
    prompts = {v: build_judge_prompt(v, ground_truth[v], {n: candidates[n][v] for n in names}, cfg["max_chars"])
               for v in volumes}
    results, pending = {}, list(volumes)
    for attempt in range(args.max_retries + 1):
        suffix = "" if attempt == 0 else ("\n\nIMPORTANT: Your previous output was invalid. "
                                          "Return ONLY a single valid JSON object that matches the schema exactly.")
        answers = judge([prompts[v] + suffix for v in pending])
        failed = []
        for v, answer in zip(pending, answers):
            try:
                results[v] = parse_scores(answer, names)
            except (ValueError, KeyError, TypeError, json.JSONDecodeError):
                failed.append(v)
        pending = failed
        if not pending:
            break
    if pending:
        print(f"Warning: no valid judgement for {len(pending)} volumes after retries: {pending[:10]}")

    summary = {}
    for name in names:
        means = {c: sum(results[v][name][c] for v in results) / max(len(results), 1) for c in CRITERIA}
        summary[name] = {**means, "overall": sum(means.values()) / len(CRITERIA)}

    out_dir = resolve_path(cfg["output_dir"])
    os.makedirs(out_dir, exist_ok=True)
    with open(os.path.join(out_dir, "llm_judge_results.json"), "w", encoding="utf-8") as f:
        json.dump({"judge": f"{cfg['backend']}:{cfg['model']}", "criteria": CRITERIA,
                   "n_samples": len(results), "failed": pending, "per_sample": results, "summary": summary},
                  f, indent=2)
    with open(os.path.join(out_dir, "llm_judge_summary.csv"), "w", newline="", encoding="utf-8") as f:
        writer = csv.writer(f)
        writer.writerow(["model", "n_samples", *CRITERIA, "overall"])
        for name in names:
            writer.writerow([name, len(results), *[f"{summary[name][c]:.3f}" for c in CRITERIA],
                             f"{summary[name]['overall']:.3f}"])
    print(json.dumps(summary, indent=2))


if __name__ == "__main__":
    main()
